package com.vocabularyai.payment.entity;

import jakarta.persistence.*;
import lombok.*;

import java.math.BigDecimal;
import java.time.LocalDateTime;

/**
 * PaymentOrder Entity - Represents a payment order created by user
 * 
 * Lifecycle:
 * 1. PENDING: Order created, waiting for payment
 * 2. PAID: Payment confirmed by PayOS webhook
 * 3. FAILED: Payment failed or expired
 * 4. CANCELLED: User or system cancelled the order
 */
@Entity
@Table(
    name = "payment_orders",
    uniqueConstraints = {
        @UniqueConstraint(name = "uk_order_code", columnNames = "order_code")
    },
    indexes = {
        @Index(name = "idx_order_user_id", columnList = "user_id"),
        @Index(name = "idx_order_status", columnList = "status"),
        @Index(name = "idx_order_created_at", columnList = "created_at"),
        @Index(name = "idx_order_code", columnList = "order_code")
    }
)
@Getter
@Setter
@ToString
@Builder
public class PaymentOrder {
    
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    private Long id;
    
    /**
     * User ID who initiated the payment
     * FK to users table (users.id)
     */
    @Column(name = "user_id", nullable = false)
    private Long userId;
    
    /**
     * Package ID being purchased
     * FK to packages table (packages.id)
     */
    @Column(name = "package_id", nullable = false)
    private Long packageId;
    
    /**
     * Unique order code generated for this payment order
     * UK constraint ensures uniqueness (e.g., ORD_1694000001_12345)
     */
    @Column(name = "order_code", nullable = false, length = 50)
    private String orderCode;
    
    /**
     * Order amount in VND (copied from package.price at order creation)
     * Used as source of truth for payment validation
     * Prevents price manipulation attacks
     */
    @Column(name = "amount", nullable = false, precision = 19, scale = 2)
    private BigDecimal amount;
    
    /**
     * Order status
     * PENDING: Waiting for payment
     * PAID: Payment successful (confirmed via webhook)
     * FAILED: Payment failed or expired
     * CANCELLED: Order cancelled
     */
    @Column(name = "status", nullable = false, length = 20)
    private String status; // PENDING, PAID, FAILED, CANCELLED
    
    /**
     * Payment link generated by PayOS
     * Provided to user for payment
     */
    @Column(name = "payment_url", columnDefinition = "TEXT")
    private String paymentUrl;
    
    /**
     * Order expiration time
     * Order is considered failed if not paid by this time
     */
    @Column(name = "expired_at")
    private LocalDateTime expiredAt;
    
    /**
     * Payment confirmation time
     * Set when payment_status becomes PAID (via webhook)
     */
    @Column(name = "paid_at")
    private LocalDateTime paidAt;
    
    /**
     * Creation timestamp
     */
    @Column(name = "created_at", nullable = false, updatable = false)
    private LocalDateTime createdAt;
    
    /**
     * Last update timestamp
     */
    @Column(name = "updated_at", nullable = false)
    private LocalDateTime updatedAt;
    
    public PaymentOrder() {
    }

    public PaymentOrder(Long id, Long userId, Long packageId, String orderCode, BigDecimal amount, String status, String paymentUrl, LocalDateTime expiredAt, LocalDateTime paidAt, LocalDateTime createdAt, LocalDateTime updatedAt) {
        this.id = id;
        this.userId = userId;
        this.packageId = packageId;
        this.orderCode = orderCode;
        this.amount = amount;
        this.status = status;
        this.paymentUrl = paymentUrl;
        this.expiredAt = expiredAt;
        this.paidAt = paidAt;
        this.createdAt = createdAt;
        this.updatedAt = updatedAt;
    }

    /**
     * JPA lifecycle callback - set createdAt before persist
     */
    @PrePersist
    protected void onCreate() {
        LocalDateTime now = LocalDateTime.now();
        this.createdAt = now;
        this.updatedAt = now;
    }
    
    /**
     * JPA lifecycle callback - set updatedAt before update
     */
    @PreUpdate
    protected void onUpdate() {
        this.updatedAt = LocalDateTime.now();
    }
}
